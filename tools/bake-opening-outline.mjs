// Bakes src/scene/opening-outline.js: the opening shot's (The watch's) focal outline per shot variant,
// so the scene can fit that shot, and place the loading line's star where the shot will show the sun,
// before the tower model loads. Run after the tower model or The watch's framing changes:
//
//   node tools/bake-opening-outline.mjs
//
// For every variant resolveDirectedShot() gives The watch over a sweep of window sizes, it measures each
// tier's tower as the live scene does (measureShot), its root at the origin (the scene lifts the
// outline to its own tower's height, openingStar()'s towerY), and keeps the measurement's convex hull:
// the fit (fitShot) only tests each point against linear limits, so the hull's vertices fit exactly as
// all of the points do. The tiers' models fit a few pixels apart in some variants, so each has its own.
// Points are stored as little-endian Int16 multiples of OUTLINE_RESOLUTION world units, base64-encoded.
import { writeFileSync } from "node:fs";
import { Vector3 } from "three";
import { ConvexHull } from "three/examples/jsm/math/ConvexHull.js";
import { glbAsset, modelBytes } from "../test/support/glb.mjs";
import { createCompleteTowerArchitecture } from "../src/scene/architecture.js";
import { DIRECTED_SHOTS, measureShot, resolveDirectedShot } from "../src/scene/directed-shots.js";
import { OUTLINE_RESOLUTION, outlineKey } from "../src/scene/opening-outline-key.js";

const opening = DIRECTED_SHOTS.tower[0];
const shots = new Map();
for (let width = 280; width <= 4000; width += 20)
  for (let height = 280; height <= 2600; height += 20) {
    const shot = resolveDirectedShot(opening, width, height);
    const key = outlineKey(shot);
    if (!shots.has(key)) shots.set(key, shot);
  }

const round = (value) => Math.round(value * 1e4) / 1e4;
const entries = [];
for (const tier of ["high", "balanced"]) {
  const tower = createCompleteTowerArchitecture({
    asset: glbAsset(modelBytes("tower", tier)),
    groundY: 0,
    footingOffset: 0,
  });
  for (const [key, shot] of shots) {
    const measured = measureShot(tower.root, shot);
    const points = [];
    for (let i = 0; i < measured.points.length; i += 3)
      points.push(new Vector3(measured.points[i], measured.points[i + 1], measured.points[i + 2]));
    const hull = new ConvexHull().setFromPoints(points);
    const vertices = new Set();
    for (const face of hull.faces) {
      let edge = face.edge;
      do {
        vertices.add(edge.head().point);
        edge = edge.next;
      } while (edge !== face.edge);
    }
    const values = new Int16Array(vertices.size * 3);
    let i = 0;
    for (const p of vertices)
      for (const v of [p.x, p.y, p.z]) {
        const q = Math.round(v / OUTLINE_RESOLUTION);
        if (Math.abs(q) > 32767) throw new Error(`${v} is out of the outline's range`);
        values[i++] = q;
      }
    entries.push({
      tier,
      key,
      target: [measured.target.x, measured.target.y, measured.target.z].map(round),
      cameraY: round(measured.cameraY),
      footing: round(measured.footing),
      groundAnchor: [measured.groundAnchor.x, measured.groundAnchor.y, measured.groundAnchor.z].map(
        round,
      ),
      height: round(measured.height),
      region: [...measured.region.min.toArray(), ...measured.region.max.toArray()].map(round),
      radius: round(measured.radius),
      points: Buffer.from(values.buffer).toString("base64"),
    });
    console.log(`${tier}: ${vertices.size} hull vertices of ${points.length} points: ${key}`);
  }
}

const source = `// Generated by tools/bake-opening-outline.mjs from images/architecture/tower-*.glb: do not edit.
// The opening shot's (The watch's) focal outline per model tier and shot variant (outlineKey()): each
// measureShot() result for the tower with its root at the origin, its points reduced to their convex
// hull (Int16 multiples of OUTLINE_RESOLUTION, little-endian, base64). opening-star.test.mjs
// re-measures the model against it.
export const OPENING_OUTLINES = Object.freeze(${JSON.stringify(entries, null, 2)});
`;
writeFileSync(new URL("../src/scene/opening-outline.js", import.meta.url), source);
console.log(`${entries.length} variants written to src/scene/opening-outline.js`);
